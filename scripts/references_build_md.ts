#!/usr/bin/env node
/**
 * Regenerate REFERENCES.md from data/references.yml, the mod overview frontmatter under
 * content/mods/<slug>/overview.md and the feature catalogs under ai/catalog/<slug>.yml.
 *
 *   node scripts/references_build_md.ts [--check]
 *
 * One section per reference repository: upstream link, license, the pinned commit, a link to the
 * mod's OKF bundle, feature counts by category, and the high-novelty features. --check exits 1 when
 * the file would change. Runs on Node 24; needs the `yaml` package (scripts/package.json).
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { parseArgs } from 'node:util';
import { parse as parseYaml } from 'yaml';

const ROOT = resolve(import.meta.dirname, '..');
const DATA_FILE = join(ROOT, 'data', 'references.yml');
const OUT_FILE = join(ROOT, 'REFERENCES.md');

interface RepoEntry { name: string; git: string; ref: string; license: string }
interface CatalogFeature { id: string; title: string; category: string; summary?: string; novelty?: string; submod?: string | null }
interface Catalog { mod: string; summary?: string; features?: CatalogFeature[] }

function slugOf(name: string): string {
  return name.toLowerCase().replace(/_/g, '-');
}

function webUrl(git: string): string {
  let u = git.trim();
  const withScheme = /^[a-z][a-z0-9+.-]*:\/\/(?:[^@/]+@)?([^/:]+)(?::\d+)?\/(.*)$/i.exec(u);
  const scpLike = /^(?:[^@/]+@)?([^/:]+):(?!\/\/)(.*)$/.exec(u);
  if (withScheme) u = `${withScheme[1]}/${withScheme[2]}`;
  else if (scpLike) u = `${scpLike[1]}/${scpLike[2]}`;
  return `https://${u.replace(/\/+$/, '').replace(/\.git$/i, '').replace(/\/+$/, '')}`;
}

function frontmatter(path: string): Record<string, unknown> | null {
  if (!existsSync(path)) return null;
  const lines = readFileSync(path, 'utf8').split(/\r?\n/);
  if (lines[0]?.trim() !== '---') return null;
  for (let i = 1; i < lines.length; i++) {
    if (lines[i]?.trim() === '---') {
      try {
        return (parseYaml(lines.slice(1, i).join('\n')) ?? {}) as Record<string, unknown>;
      } catch {
        return null;
      }
    }
  }
  return null;
}

function build(): string {
  const data = parseYaml(readFileSync(DATA_FILE, 'utf8')) as { repos: RepoEntry[] };
  const out: string[] = [];
  out.push('# Reference repositories');
  out.push('');
  out.push('Upstream KSA mod repositories analyzed for this knowledge base, with what was found interesting in each.');
  out.push('Generated by `scripts/references_build_md.ts` from `data/references.yml`, the mod overviews under');
  out.push('`content/mods/<slug>/overview.md` and the feature catalogs under `ai/catalog/<slug>.yml`; do not edit by hand.');
  out.push('');
  out.push('| Mod | Bundle | License | Features | Pinned commit |');
  out.push('|---|---|---|---|---|');
  const sections: string[] = [];
  for (const repo of [...data.repos].sort((a, b) => a.name.localeCompare(b.name, 'en', { sensitivity: 'base' }))) {
    const slug = slugOf(repo.name);
    const overviewPath = join(ROOT, 'content', 'mods', slug, 'overview.md');
    const fm = frontmatter(overviewPath);
    const catalogPath = join(ROOT, 'ai', 'catalog', `${slug}.yml`);
    const catalog = existsSync(catalogPath) ? (parseYaml(readFileSync(catalogPath, 'utf8')) as Catalog) : null;
    const features = catalog?.features ?? [];
    const web = webUrl(repo.git);
    const title = (fm?.title as string | undefined) ?? repo.name;
    out.push(`| [${title}](${web}) | [content/mods/${slug}](content/mods/${slug}/overview.md) | ${repo.license} | ${features.length} | \`${repo.ref.slice(0, 12)}\` |`);

    const byCat = new Map<string, number>();
    for (const f of features) byCat.set(f.category, (byCat.get(f.category) ?? 0) + 1);
    const cats = [...byCat.entries()].sort((a, b) => b[1] - a[1]).map(([c, n]) => `${c} (${n})`).join(', ');
    const high = features.filter((f) => f.novelty === 'high');
    const sec: string[] = [];
    sec.push(`## ${title}`);
    sec.push('');
    sec.push(`- Upstream: <${web}> (${repo.license}), pinned at \`${repo.ref}\``);
    sec.push(`- Bundle: [content/mods/${slug}/overview.md](content/mods/${slug}/overview.md)`);
    if (fm?.loader) sec.push(`- Loader: ${String(fm.loader)}${fm.mod_id ? `, mod id \`${String(fm.mod_id)}\`` : ''}${fm.tested_against ? `, targets KSA ${String(fm.tested_against)}` : ''}`);
    if (fm?.description) sec.push(`- ${String(fm.description)}`);
    if (features.length > 0) sec.push(`- Features: ${features.length} across ${cats}`);
    if (high.length > 0) {
      sec.push('- Notable techniques:');
      for (const f of high.slice(0, 12)) {
        const rel = `content/${f.id}.md`;
        sec.push(`  - [${f.title}](${rel})${f.summary ? ` - ${String(f.summary).replace(/\s+/g, ' ').trim()}` : ''}`);
      }
      if (high.length > 12) sec.push(`  - and ${high.length - 12} more high-novelty features in the bundle index`);
    }
    sec.push('');
    sections.push(sec.join('\n'));
  }
  out.push('');
  out.push(...sections);
  out.push('Game sources: the decompiled Kitten Space Agency assemblies (see `game:` pins in every concept frontmatter; build and commit recorded there).');
  out.push('');
  return out.join('\n');
}

function main(): number {
  const args = parseArgs({ options: { check: { type: 'boolean' } } });
  const content = build();
  const current = existsSync(OUT_FILE) ? readFileSync(OUT_FILE, 'utf8') : '';
  if (args.values.check) {
    const same = current === content;
    process.stdout.write(same ? 'REFERENCES.md is up to date\n' : 'REFERENCES.md is out of date\n');
    return same ? 0 : 1;
  }
  if (current !== content) {
    writeFileSync(OUT_FILE, content, 'utf8');
    process.stdout.write('wrote REFERENCES.md\n');
  } else process.stdout.write('REFERENCES.md unchanged\n');
  return 0;
}

process.exit(main());
